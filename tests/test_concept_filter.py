    def test_事件型被归类为_event(self):
        for name in ["业绩预升", "业绩预降", "股权激励", "重组概念",
                     "整体上市", "资产注入", "送转潜力", "摘帽概念",
                     "本月解禁", "出口退税"]:
            self.assertEqual(classify_concept(name), EVENT, name)

